"""
Build the README block diagram from real model and pipeline outputs.

    python scripts/make_figure.py      # writes docs/figures/pipeline_block_diagram.png

Every panel is produced by the code in cardiosim/ (no hand-drawn images): the simulated inputs
(latent states, electrophysiology, synthetic microscopy), the measurement pipeline outputs
(segmentation, sarcomere spectrum, optical flow, calcium kinetics) and the statistical outputs
read from data/. Requires matplotlib (not needed by the app itself).
"""
import os
import sys
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch  # noqa: E402

from cardiosim import analysis as A  # noqa: E402
from cardiosim import ep  # noqa: E402
from cardiosim.model import CultureParams, latent, make_study  # noqa: E402
from cardiosim.pipeline import run_well_day  # noqa: E402
from cardiosim.stats import day_summary, hill, hill_fit, kaplan_meier, state_space, turning_point  # noqa: E402

OUT = os.path.join(ROOT, "docs", "figures")
C = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#8a5cd6", "#d63a7a", "#3bb3c4", "#7a7a72"]
BAND = {"sim": "#fdecef", "mea": "#eaf2fc", "inf": "#eaf7f0", "in": "#fff4e5"}
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.titlesize": 11, "axes.titleweight": "bold",
                     "axes.spines.top": False, "axes.spines.right": False, "axes.labelsize": 9.5})


def clean(ax):
    ax.set_xticks([])
    ax.set_yticks([])
    for s in ax.spines.values():
        s.set_visible(False)


def main():
    os.makedirs(OUT, exist_ok=True)
    p = CultureParams()
    wells = make_study(p)
    print("simulating example well-days …", flush=True)
    runs = {d: run_well_day(p, wells[0], d, keep=True) for d in (2, 5, 8)}
    o5, a5 = runs[5]
    study = pd.read_csv(os.path.join(ROOT, "data", "study.csv"))
    cells = pd.read_csv(os.path.join(ROOT, "data", "cells.csv"))
    dose = pd.read_csv(os.path.join(ROOT, "data", "dose_response.csv"))

    fig = plt.figure(figsize=(22, 15.6), dpi=130)
    fig.patch.set_facecolor("white")
    # band backgrounds (figure coordinates)
    bands = [("sim", 0.655, 0.29, "①  SIMULATE — in-silico hiPSC-CM culture (ground truth)"),
             ("mea", 0.345, 0.29, "②  MEASURE — analysis pipeline (same code for your uploads)"),
             ("inf", 0.035, 0.29, "③  INFER — statistics, validation and virtual experiments")]
    for key, y, h, title in bands:
        fig.add_artist(FancyBboxPatch((0.115, y), 0.875, h, boxstyle="round,pad=0.004,rounding_size=0.012",
                                      transform=fig.transFigure, facecolor=BAND[key], edgecolor="#cfcfcf", lw=1, zorder=0))
        fig.text(0.125, y + h - 0.016, title, fontsize=15, fontweight="bold", color="#222", va="top")
    fig.text(0.5, 0.985, "Cardiomyocyte Maturation & Degeneration Lab — end-to-end pipeline with real model outputs",
             ha="center", va="top", fontsize=19, fontweight="bold")
    fig.text(0.5, 0.962, "Every panel below is generated by the app's own code (cardiosim/) for the default 6-well, 8-day study; "
             "culture data are simulated, analysis code also runs on real uploads.", ha="center", va="top", fontsize=11.5, color="#555")

    # left column: inputs
    def box(x, y, w, h, fc, title, lines):
        fig.add_artist(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.004,rounding_size=0.01", transform=fig.transFigure,
                                      facecolor=fc, edgecolor="#999", lw=1.2))
        fig.text(x + w / 2, y + h - 0.012, title, ha="center", va="top", fontsize=11.5, fontweight="bold")
        fig.text(x + w / 2, y + h - 0.042, "\n".join(lines), ha="center", va="top", fontsize=9.6, color="#333", linespacing=1.45)
    box(0.008, 0.70, 0.098, 0.20, "#fdecef", "Model inputs", ["6 replicate wells", "55 seeded cells/field", "maturation &", "damage kinetics",
                                                               "coupling, hazard,", "pacemaker fraction", "(Culture simulator", "sliders)"])
    box(0.008, 0.39, 0.098, 0.20, BAND["in"], "Your data", ["beating-cell video", "MP4 · AVI · MOV ·", "TIFF stack · GIF", "",
                                                             "fluorescence image", "α-actinin + nuclei", "TIFF · PNG · JPG"])
    box(0.008, 0.08, 0.098, 0.20, "#eaf7f0", "Outputs", ["22 phenotypes ×", "6 wells × 8 days", "validated metrics", "CSV downloads",
                                                          "model card", "figures for", "papers/theses"])
    for (x0, y0, x1, y1) in [(0.106, 0.80, 0.118, 0.80), (0.106, 0.49, 0.118, 0.49), (0.118, 0.18, 0.106, 0.18)]:
        fig.add_artist(FancyArrowPatch((x0, y0), (x1, y1), transform=fig.transFigure, arrowstyle="-|>", mutation_scale=22, lw=2.2, color="#555"))
    for y0, y1 in [(0.655, 0.637), (0.345, 0.327)]:
        fig.add_artist(FancyArrowPatch((0.55, y0 + 0.004), (0.55, y1 - 0.004), transform=fig.transFigure, arrowstyle="-|>",
                                       mutation_scale=30, lw=3, color="#444"))

    def axes(row_y, i, widths=(1, 1, 1, 1, 1), pad=0.028):
        x0, total = 0.13, 0.845
        unit = (total - pad * (len(widths) - 1)) / sum(widths)
        left = x0 + sum(widths[:i]) * unit + i * pad
        return fig.add_axes([left, row_y, widths[i] * unit, 0.215])
    W1 = (0.85, 0.75, 0.85, 1.75, 0.8)

    # ---------------------------------------------------------------- band 1: simulate
    y1 = 0.672
    ax = axes(y1, 0, W1)
    t = np.linspace(0, 9, 200)
    for w in wells:
        M, D = latent(t, p, w.u, w.v)
        ax.plot(t, M, color=C[0], lw=1.6 if w.index == 0 else 0.8, alpha=1 if w.index == 0 else 0.4)
        ax.plot(t, D, color=C[5], lw=1.6 if w.index == 0 else 0.8, alpha=1 if w.index == 0 else 0.4)
    ax.text(1.0, 0.85, "maturation M", color=C[0], fontsize=9.5)
    ax.text(5.6, 0.25, "damage D", color=C[5], fontsize=9.5)
    ax.set_xlabel("culture day")
    ax.set_title("a  Latent states per well")

    ax = axes(y1, 1, W1)
    v = a5["sim"]["v"]
    ex = a5["tissue"]["excitable"]
    frac = np.array([(f[ex] > 0.5).mean() for f in v])
    half = np.arange(len(v)) > len(v) // 2
    k = int(np.argmin(np.where(half, np.abs(frac - 0.45), 9)))      # a frame with the wave half-way across
    img = np.where(a5["tissue"]["excitable"], v[k], np.nan)
    ax.imshow(img, cmap="coolwarm", vmin=-2.1, vmax=2.0)
    clean(ax)
    ax.set_title("b  FHN lattice: wave in transit")
    ax.text(0.02, 0.02, f"Kuramoto R = {o5['kuramoto_R']:.2f}", transform=ax.transAxes, fontsize=9, color="k",
            bbox=dict(fc="white", ec="none", alpha=0.85))

    ax = axes(y1, 2, W1)
    am = a5["functional"]["activation_map"]
    im = ax.imshow(am, cmap="turbo")
    clean(ax)
    ax.set_title("c  Activation map (day 5)")
    cb = fig.colorbar(im, ax=ax, fraction=0.045, pad=0.02)
    cb.set_label("ms", fontsize=8)
    cb.ax.tick_params(labelsize=7)

    ax = axes(y1, 3, W1)
    strip = np.concatenate([runs[d][1]["image"]["rgb"][120:648, 120:648] for d in (2, 5, 8)], axis=1)
    ax.imshow(strip)
    clean(ax)
    for j, d in enumerate((2, 5, 8)):
        ax.text(j * 528 + 14, 44, f"day {d}", color="white", fontsize=10, fontweight="bold")
    ax.set_title("d  Synthetic α-actinin / DAPI images")

    ax = axes(y1, 4, W1)
    ax.imshow(a5["frames"][int(np.argmax(a5["gt_tension"]))], cmap="gray")
    clean(ax)
    ax.set_title("e  Bright-field beating movie frame")
    ax.text(0.02, 0.02, "256 px · 40 fps · 5 s", transform=ax.transAxes, fontsize=9, bbox=dict(fc="white", ec="none", alpha=0.85))

    # ---------------------------------------------------------------- band 2: measure
    y2 = 0.362
    from skimage.segmentation import find_boundaries
    ax = axes(y2, 0)
    rgb = a5["image"]["rgb"].copy()
    lab, nuc, frag = a5["masks"]
    rgb[find_boundaries(lab, mode="outer")] = [255, 255, 0]
    rgb[find_boundaries(nuc, mode="outer")] = [255, 0, 255]
    ax.imshow(rgb[100:612, 100:612])
    clean(ax)
    ax.set_title("f  Watershed segmentation")
    ax.text(0.02, 0.02, f"{o5['img_n_cells']} cells · S = {o5['img_orientation_order']:.2f}", transform=ax.transAxes, fontsize=9,
            bbox=dict(fc="white", ec="none", alpha=0.85))

    ax = axes(y2, 1)
    df = a5["cell_table"]
    best = df.sort_values("sarcomere_score", ascending=False).iloc[0]
    sp = A.sarcomere_spectrum(a5["image"]["actinin"], lab == best.cell, a5["image"]["um_per_px"])
    f, pw = sp["radial"]
    ax.semilogy(f, pw, color=C[0], lw=1.6)
    ax.axvspan(1 / 2.6, 1 / 1.3, color=C[2], alpha=0.12)
    ax.axvline(1 / sp["sarcomere_length_um"], color=C[1], ls=":", lw=1.5)
    ax.text(1 / sp["sarcomere_length_um"] + 0.03, pw.max() * 0.02, f"SL = {sp['sarcomere_length_um']:.2f} µm", color=C[1], fontsize=9.5)
    ax.set_xlabel("spatial frequency (cycles/µm)")
    ax.set_yticks([])
    ax.set_title("g  Sarcomere 2-D FFT spectrum")
    ins = ax.inset_axes([0.55, 0.55, 0.43, 0.43])
    y0_, x0_, y1_, x1_ = best.bbox
    cy, cx = (y0_ + y1_) // 2, (x0_ + x1_) // 2
    ins.imshow(a5["image"]["actinin"][cy - 40:cy + 40, cx - 40:cx + 40], cmap="Greens_r")
    clean(ins)

    ax = axes(y2, 2)
    ax.imshow(a5["motion"]["max_disp_map"], cmap="inferno")
    clean(ax)
    ax.set_title("h  Optical-flow peak displacement")

    ax = axes(y2, 3)
    mo = a5["motion"]
    ax.plot(mo["t_s"], mo["displacement_um"], color=C[0], lw=1.8, label="optical flow")
    gt = a5["gt_tension"]
    ax.plot(mo["t_s"], gt / gt.max() * mo["displacement_um"].max(), color=C[1], ls=":", lw=1.6, label="true tension")
    ax.plot(mo["t_s"][a5["peaks"]], mo["displacement_um"][a5["peaks"]], "v", color=C[5], ms=9, label="detected beats")
    ax.set_xlabel("time (s)")
    ax.set_ylabel("displacement (µm)")
    ax.legend(fontsize=8, frameon=False, loc="upper right")
    ax.set_title(f"i  Beat detection · {o5['mot_beat_rate_bpm']:.0f} bpm")

    ax = axes(y2, 4)
    tis, sim = a5["tissue"], a5["sim"]
    ii, jj = np.nonzero(tis["excitable"])
    rng = np.random.default_rng(3)
    for n, s_ in enumerate(rng.choice(len(ii), 5, replace=False)):
        i, j = ii[s_], jj[s_]
        ax.plot(sim["t_frames"] / 1000, tis["amp"][i, j] * sim["ca"][:, i, j], lw=1.1, color=C[n % 8], alpha=0.85)
    ax.set_xlabel("time (s)")
    ax.set_ylabel("ΔF/F₀")
    ax.set_title(f"j  Single-cell Ca²⁺ · τ = {o5['ca_tau_decay_ms']:.0f} ms")

    # ---------------------------------------------------------------- band 3: infer
    y3 = 0.052
    ax = axes(y3, 0)
    for key, col, lab_ in [("kuramoto_R", C[0], "synchrony R"), ("img_striated_fraction", C[2], "striated cells")]:
        s = day_summary(study, key)
        ax.plot(s.day, s["mean"], "-o", color=col, lw=2, ms=4, label=lab_)
        ax.fill_between(s.day, s.ci_lo, s.ci_hi, color=col, alpha=0.18)
    tp = turning_point(study, "kuramoto_R", n_boot=200)
    ax.axvspan(*tp["ci"], color=C[1], alpha=0.12)
    ax.axvline(tp["tau"], color=C[1], ls="--", lw=1.4)
    ax.text(tp["tau"] + 0.1, 0.05, f"turning point\nday {tp['tau']:.1f}", color=C[1], fontsize=8.5)
    ax.set_xlabel("culture day")
    ax.set_ylim(0, 1.05)
    ax.legend(fontsize=8, frameon=False, loc="upper left")
    ax.set_title("k  Trajectories (mean ± 95 % CI)")

    ax = axes(y3, 1)
    feats = ["kuramoto_R", "rate_dispersion", "img_striated_fraction", "img_orientation_order", "img_mean_aspect_ratio",
             "img_n_fragments", "ca_amplitude_dff", "ca_tau_decay_ms", "mot_amplitude_um", "img_n_cells"]
    ss = state_space(study, feats)
    d = ss["data"]
    for w, g in d.sort_values("day").groupby("well"):
        ax.plot(g.PC1, g.PC2, color="#bbb", lw=0.8, zorder=1)
    names = {1: "immature", 2: "mature", 3: "degenerating"}
    for s_ in sorted(d.state.unique()):
        m = d.state == s_
        ax.scatter(d.PC1[m], d.PC2[m], s=36, color=C[[0, 2, 5][(s_ - 1) % 3]], label=names.get(s_, f"state {s_}"), zorder=2)
    ax.set_xlabel(f"PC1 ({ss['explained'][0]:.0%})")
    ax.set_ylabel(f"PC2 ({ss['explained'][1]:.0%})")
    ax.legend(fontsize=8, frameon=False)
    ax.set_title(f"l  Cell states (GMM, BIC → k = {ss['k']})")

    ax = axes(y3, 2)
    ok = study.dropna(subset=["img_sarcomere_length_um"])
    ax.scatter(study.true_n_cells, study.img_n_cells, s=16, color=C[0], label="attached cells")
    ax.plot([15, 55], [15, 55], color="#777", ls=":")
    ax.set_xlabel("ground truth")
    ax.set_ylabel("measured")
    ccc = lambda m, t: 2 * np.cov(m, t)[0, 1] / (m.var(ddof=1) + t.var(ddof=1) + (m.mean() - t.mean()) ** 2)  # noqa: E731
    ax.text(0.04, 0.9, f"cell count CCC = {ccc(study.img_n_cells, study.true_n_cells):.3f}", transform=ax.transAxes, fontsize=9)
    b = (ok.img_sarcomere_length_um - ok.true_med_sarcomere_length)
    ax.text(0.04, 0.80, f"sarcomere length bias = {b.mean():+.3f} µm", transform=ax.transAxes, fontsize=9)
    ax.text(0.04, 0.70, f"beat sensitivity (days 4–7) = {study[study.day.between(4, 7)].val_beat_sensitivity.mean():.0%}",
            transform=ax.transAxes, fontsize=9)
    ax.set_title("m  Validation vs ground truth")

    ax = axes(y3, 3)
    hf = hill_fit(dose.conc_uM.values, dose.kuramoto_R.values)
    cplot = dose.conc_uM.replace(0, 0.03)
    ax.scatter(cplot, dose.kuramoto_R, color=C[4], s=22, zorder=2)
    cs = np.logspace(-1.6, 1.6, 200)
    ax.plot(cs, hill(cs, *hf["popt"]), color=C[1], lw=2)
    ax.axvline(hf["ic50"], color=C[1], ls=":")
    ax.axvline(1.5, color="#555", ls="--")
    ax.set_xscale("log")
    ax.text(hf["ic50"] * 1.15, 0.85, f"functional\nIC₅₀ {hf['ic50']:.1f} µM", color=C[1], fontsize=8.5)
    ax.text(0.06, 0.32, "molecular\nIC₅₀ 1.5 µM", color="#555", fontsize=8.5)
    ax.set_xlabel("gap-junction blocker (µM)")
    ax.set_ylabel("synchrony R")
    ax.set_title("n  Virtual dose–response")

    ax = axes(y3, 4)
    c = cells[np.isfinite(cells.attach_day) & (cells.attach_day < 8) & (cells.death_day > cells.attach_day)].copy()
    c["time"] = np.minimum(c.death_day, 8) - c.attach_day
    c["event"] = c.death_day <= 8
    km = kaplan_meier(c.time, c.event)
    ax.step(km.t, km.S, where="post", color=C[5], lw=2.2)
    ax.fill_between(km.t, km.lo, km.hi, step="post", color=C[5], alpha=0.15)
    ax.set_ylim(0, 1.02)
    ax.set_xlabel("days since attachment")
    ax.set_ylabel("survival")
    ax.set_title("o  Kaplan–Meier cell survival")

    path = os.path.join(OUT, "pipeline_block_diagram.png")
    fig.savefig(path, dpi=110, facecolor="white")
    print("wrote", path)


if __name__ == "__main__":
    main()
